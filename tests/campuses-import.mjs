import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import {parseCoordinate,prepareCampuses} from '../tools/universities-import/prepare-campuses.mjs';
import {validateCampuses,main} from '../tools/universities-import/import-campuses.mjs';
assert.equal(parseCoordinate('-23561043','latitude'),-23.561043);
assert.equal(parseCoordinate('21,9536° S','latitude'),-21.9536);
assert.equal(parseCoordinate('-22.8904° S','latitude'),-22.8904);
assert.equal(parseCoordinate("'-46.8073°",'longitude'),-46.8073);
assert.equal(parseCoordinate(`23°57'14.5"S`,'latitude'),-23.95402778);
assert.equal(parseCoordinate("22°00'84.67 S",'latitude'),null);
assert.equal(parseCoordinate("47°89'77.78 W",'longitude'),null);
assert.equal(parseCoordinate('','latitude'),null);
assert.equal(parseCoordinate('23° W','latitude'),null);
const source=JSON.parse(await readFile(new URL('../tools/universities-import/campuses-source.json',import.meta.url),'utf8'));
const universities=JSON.parse(await readFile(new URL('../tools/universities-import/universities.json',import.meta.url),'utf8'));
const prepared=prepareCampuses(source,universities.universities.map(item=>item.id));
assert.equal(prepared.campuses.length,28);
assert.equal(prepared.campuses.find(item=>item.id==='usp-piracicaba').name,'Piracicaba');
assert.equal(prepared.campuses.find(item=>item.id==='usp-sao-carlos').name,'São Carlos');
assert.equal(prepared.campuses.filter(item=>item.latitude!==null).length,27);
assert.equal(prepared.issues.length,2);
assert.equal(prepared.campuses.find(item=>item.id==='usp-sao-carlos').latitude,null);
assert.ok(prepared.campuses.some(item=>item.id==='usp-cidade-universitaria'));
validateCampuses(prepared);
assert.throws(()=>validateCampuses({...prepared,campuses:[prepared.campuses[0],prepared.campuses[0]]}),/duplicado/);
assert.throws(()=>validateCampuses({...prepared,campuses:[{...prepared.campuses[0],latitude:200}]}),/Coordenadas/);
await assert.rejects(main(['--write']),/projeto/);
console.log('OK: extração, 28 campi, 27 localizações, DMS, correção autorizada, exclusão da linha sem unidade e validação de importação.');

const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
(async () => {
  const source = fs.readFileSync('services/preferences.js','utf8');
  const prefs = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
  let profile = {preferences:prefs.normalizePreferences({cityIds:['campinas','sao-carlos'],institutionTypes:['privada'],modeIds:['ead'],courseIds:['medicina','direito'],periodIds:['noite']})};
  let failed = false, writes = 0;
  const catalog={getCourse: value => ['medicina','direito'].includes(value) ? {id:value,value} : null};
  const context = vm.createContext({URLSearchParams,Error,getProfile:async()=>profile,updatePreferences:async value=>{ if(failed) throw new Error('offline'); writes++; profile.preferences=value; return value; },...prefs});
  const code=fs.readFileSync('services/search-preferences.js','utf8').replace(/^import .*;\r?\n/gm,'').replaceAll('export async function','async function');
  vm.runInContext(code,context);
  const state=await context.loadSearchPreferences(new URLSearchParams('city=sao-paulo&type=publica&course=velho&busca=nome&sort=name'),catalog);
  assert.deepEqual(state.params.getAll('city'),['campinas','sao-carlos']);
  assert.deepEqual(state.params.getAll('course'),['medicina','direito']);
  assert.equal(state.params.get('type'),'particular');
  assert.equal(state.params.get('busca'),'nome');
  assert.equal(state.params.get('sort'),'name');
  await context.saveSearchPreferences(new URLSearchParams('city=sao-paulo&course=direito&mode=presencial&type=publica&admission=sisu'),catalog);
  assert.deepEqual(profile.preferences.periodIds,['noite']);
  assert.deepEqual(profile.preferences.admissionMethodIds,['sisu']);
  const next=await context.loadSearchPreferences(new URLSearchParams(),catalog);
  assert.equal(next.params.get('city'),'sao-paulo');
  assert.equal(next.params.get('course'),'direito');
  await context.saveSearchPreferences(new URLSearchParams('city=&course=&mode=&type=&admission='),catalog);
  assert.deepEqual(profile.preferences.cityIds,[]);
  assert.deepEqual(profile.preferences.courseIds,[]);
  failed=true;
  await assert.rejects(context.saveSearchPreferences(new URLSearchParams('city=campinas'),catalog));
  assert.deepEqual(profile.preferences.cityIds,[]);
  assert.equal(writes,2);
  profile=null;
  await assert.rejects(context.loadSearchPreferences(new URLSearchParams(),catalog),{code:'profile/incomplete'});
  for(const file of ['filtros','buscar-universidades']) new vm.Script(fs.readFileSync(`src/scripts/pages/${file}.js`,'utf8'));
  console.log('OK: preferências compartilhadas, múltiplas seleções, persistência, limpeza e falha de gravação.');
})().catch(error=>{console.error(error);process.exitCode=1;});

const assert = require('node:assert/strict');
const fs = require('node:fs');
const load = file => import(`data:text/javascript;base64,${Buffer.from(fs.readFileSync(file)).toString('base64')}`);
(async () => {
  const prefs = await load('services/preferences.js');
  const {createRegistrationService} = await load('services/registration.js');
  const {accountDestination} = await load('services/account-ui.js');
  const preferences = prefs.signupPreferences({institutionType:'todas', cityIds:['sao-paulo','campinas','campinas'], modeIds:['presencial','ead'], periodIds:['noite','sem-preferencia'], courseIds:['medicina','direito']});
  assert.deepEqual(preferences.cityIds,['sao-paulo','campinas']);
  assert.deepEqual(preferences.institutionTypes,[]);
  assert.deepEqual(preferences.periodIds,['noite']);
  const catalog = {getCourse: value => ['medicina','direito'].includes(value) ? {id:value,value} : null};
  const roundtrip = prefs.preferencesFromFilters(prefs.preferencesToFilters(preferences,catalog),preferences,catalog);
  assert.deepEqual(roundtrip,preferences);
  assert.deepEqual(prefs.normalizePreferences({...preferences,discoveringCourses:true}).courseIds,[]);
  const root = new URL('https://to-dentro.github.io/app/');
  for (const retorno of ['https://evil.example/','/elsewhere','../','/app/src/pages/login.html']) assert.equal(accountDestination('?retorno='+encodeURIComponent(retorno),root,'src/pages/perfil.html'),root+'src/pages/perfil.html');
  assert.equal(accountDestination('?retorno=/app/src/pages/salvos.html',root,'index.html'),root+'src/pages/salvos.html');
  let user = null, creates = 0, saves = 0, fail = true, written;
  const service = createRegistrationService({getCurrentUser:()=>user, createAccount:async email => { creates++; user={uid:'u1',email}; return {user}; }, setDisplayName:async()=>{}, saveProfile:async payload => {saves++; written=payload; if(fail) throw Object.assign(new Error(),{code:'permission-denied'});}});
  const input = {displayName:' Aluna ',email:'ALUNA@example.com',password:'secret-for-test',preferences,termsAccepted:true};
  const first = service.register(input);
  assert.equal(service.register(input),first);
  await assert.rejects(first,error=>error.accountCreated && error.code==='permission-denied');
  assert.equal(creates,1);
  fail=false;
  await service.register(input);
  assert.equal(creates,1); assert.equal(saves,2);
  assert.deepEqual(Object.keys(written).sort(),['displayName','preferences']);
  assert.equal(written.displayName,'Aluna');
  assert.equal(user.email,'aluna@example.com');
  await assert.rejects(service.register({...input,termsAccepted:false}),{code:'signup/terms-required'});
  await assert.rejects(service.register({...input,email:'outra@example.com'}),{code:'signup/session-conflict'});
  console.log('OK: preferências, retorno seguro, cadastro sem duplicação, falha de perfil e retomada.');
})().catch(error=>{console.error(error);process.exitCode=1;});

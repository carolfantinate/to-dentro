import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {prepareCourses,parseResults} from '../tools/universities-import/prepare-courses.mjs';
import {courseDocuments,main} from '../tools/universities-import/import-courses.mjs';
const load=async file=>JSON.parse((await readFile(new URL('../tools/universities-import/'+file,import.meta.url),'utf8')).replace(/^\uFEFF/,''));
const source=await load('courses-source.json'), campuses=(await load('campuses.json')).campuses, mapping=await load('courses-campus-mapping.json');
const data=prepareCourses(source,campuses,mapping);
assert.deepEqual(data,await load('courses.json'));
assert.equal(data.courses.length,4);assert.equal(data.offerings.length,12);assert.equal(data.processes.length,3);assert.equal(data.cutoffScores.length,29);
assert.equal(courseDocuments(data).length,48);
const law=data.offerings.filter(item=>item.courseId==='direito' && item.campusId==='usp-cidade-universitaria');
assert.equal(law.length,2);assert.notEqual(law[0].id,law[1].id);assert.deepEqual(law.map(item=>item.seats),[225,235]);
assert.ok(law.every(item=>item.campusAssignmentProvisional));
assert.ok(data.offerings.every(item=>item.curriculumUrl===null));
assert.equal(data.offerings.find(item=>item.campusId==='usp-bauru').seatsPeriod,null);
const computing=data.offerings.find(item=>item.campusId==='usp-sao-carlos' && item.courseId==='ciencia-da-computacao');
assert.equal(computing.durationSemesters,10);
const med=data.offerings.find(item=>item.campusId==='usp-cidade-universitaria' && item.courseId==='medicina');
const medScores=data.cutoffScores.filter(item=>item.offeringId===med.id);
assert.equal(medScores.find(item=>item.processId==='usp-enem-usp').value,840.35);
assert.equal(medScores.find(item=>item.processId==='usp-fuvest' && item.stageId==='fase-1').value,80);
const second=medScores.find(item=>item.stageId==='fase-2');assert.equal(second.value,null);assert.equal(second.minimum,80);assert.equal(second.maximum,88);
const prova=medScores.filter(item=>item.processId==='usp-provao-paulista');
assert.deepEqual(prova.map(item=>item.selectionCategoryId).sort(),['l1','l2','l3','l4']);
assert.equal(prova.find(item=>item.selectionCategoryId==='l3').minimum,76);
assert.ok(data.cutoffScores.every(item=>item.scale===null));
const later=structuredClone(source);later.rows.push({university:'UNESP',course:'Incompleto'});
assert.deepEqual(prepareCourses(later,campuses,mapping),data);
assert.throws(()=>prepareCourses({...source,rows:source.rows.slice(0,-1)},campuses,mapping),/Limite/);
const duplicate=structuredClone(source);duplicate.rows[4].period='Matutino';assert.throws(()=>prepareCourses(duplicate,campuses,mapping),/duplicada/);
assert.throws(()=>prepareCourses(source,campuses,{usp:{}}),/Campus/);
assert.throws(()=>parseResults('Fuvest / 2026 / ampla / indefinido',{universityId:'usp',offeringId:'oferta'}),/Resultado/);
const broken=structuredClone(data);broken.cutoffScores[0].campusId='outro';assert.throws(()=>courseDocuments(broken),/vínculo/);
await assert.rejects(main(['--write']),/project/);
console.log('OK: limite da aba, 12 ofertas por campus/turno, 29 resultados por processo/ano/modalidade/fase, faixas, IDs e vínculos.');

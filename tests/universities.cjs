const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
(async()=>{
  const fixture = JSON.parse(fs.readFileSync('tools/universities-import/universities.json','utf8'));
  const serviceSource = fs.readFileSync('services/universities.js','utf8').replace(/^import .*;\r?\n/gm,'');
  const context = vm.createContext({URL, db:{}, collection:(_db,name)=>{assert.equal(name,'universities');return name;}, getDocsFromServer:async()=>({docs:fixture.universities.map(record=>({id:record.id,data:()=>record}))})});
  vm.runInContext(serviceSource.replaceAll('export function','function').replaceAll('export async function','async function'),context);
  const mock={id:'usp',description:'Texto antigo',website:'https://old.example/',city:'São Paulo',courses:['Medicina'],mode:'presencial',periods:['integral'],photos:[]};
  const records=await context.getUniversities([mock]);
  assert.equal(records.length,7);
  const usp=records.find(record=>record.id==='usp');
  assert.equal(usp.description,fixture.universities[0].description);
  assert.equal(usp.website,'https://www.usp.br/');
  assert.equal(usp.category,'Estadual');assert.equal(usp.free,true);assert.equal(usp.public,true);
  assert.equal(usp.courses[0],'Medicina');
  const ufabc=records.find(record=>record.id==='ufabc');assert.equal(ufabc.city,'');assert.equal(ufabc.mode,null);assert.equal(ufabc.courses.length,0);
  assert.equal(context.mergeUniversity({...fixture.universities[0],officialWebsite:'javascript:alert(1)'}).website,'');
  const app=vm.createContext({window:{}});
  vm.runInContext(fs.readFileSync('src/data/mock-data.js','utf8'),app);
  vm.runInContext(fs.readFileSync('src/data/catalog.js','utf8'),app);
  app.window.ToDentroData.applyUniversities(records);
  assert.equal(app.window.ToDentroData.getUniversity('usp').description,usp.description);
  assert.equal(app.window.ToDentroData.views.universities.length,7);
  assert.ok(Object.isFrozen(app.window.ToDentroData.views.universities));
  assert.ok(app.window.ToDentroData.getOfferings({universityId:'usp'}).length>0);
  const rules=fs.readFileSync('firestore.rules','utf8');
  assert.match(rules,/match \/universities\/\{universityId\} \{\s*allow get, list: if true;\s*allow create, update, delete: if false;/);
  for(const file of fs.readdirSync('src/scripts/pages').filter(name=>name.endsWith('.js')))new vm.Script(fs.readFileSync(`src/scripts/pages/${file}`,'utf8'));
  console.log('OK: consulta do catálogo, sete registros, campos reais, preservação dos mocks acadêmicos, URLs seguras e sintaxe das páginas.');
})().catch(error=>{console.error(error);process.exitCode=1;});
